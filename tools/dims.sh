#!/bin/sh
# Write data/figs.js: pixel size of every figure in img/ (read by CVS.fig for width/height attributes).
cd "$(dirname "$0")/.."
{ echo "/* Generated by tools/dims.sh from img/*.jpg. */"; echo "CVS.dims = {"
  sips -g pixelWidth -g pixelHeight img/*.jpg 2>/dev/null | paste - - - | sed -E "s#^.*/img/([^[:space:]]+)\.jpg[[:space:]]+pixelWidth: ([0-9]+)[[:space:]]+pixelHeight: ([0-9]+)#  \"\1\": [\2, \3],#"
  echo "};"; } > data/figs.js
grep -c '": \[' data/figs.js
